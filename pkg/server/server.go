// Package server предоставляет функции для запуска веб-сервера.
//
// Пакет содержит логику инициализации и запуска HTTP сервера
// для планировщика задач. Сервер обслуживает как статические
// файлы фронтенда, так и REST API endpoints.
//
// Сервер поддерживает настройку порта через переменную окружения
// TODO_PORT. По умолчанию используется порт 7540.
//
// Пример использования:
//
//	// Запуск сервера с настройками по умолчанию
//	server.StartServer()
//
//	// Или с кастомным портом
//	os.Setenv("TODO_PORT", "8080")
//	server.StartServer()
package server

import (
	"fmt"
	"log"
	"net/http"
	"os"

	"todo/pkg/api"
)

const (
	defaultPort = "7540"  // Порт по умолчанию для веб-сервера
	webDir      = "./web" // Директория со статическими файлами фронтенда
)

// StartServer запускает веб-сервер планировщика задач.
//
// Функция выполняет следующие действия:
//   - Читает порт из переменной окружения TODO_PORT или использует 7540
//   - Инициализирует API обработчики
//   - Настраивает обслуживание статических файлов из директории web/
//   - Запускает HTTP сервер
//
// Функция блокирующая - сервер работает до завершения программы.
// При ошибке запуска сервера программа завершается с log.Fatal.
func StartServer() {
	// Получаем порт из переменной окружения или используем по умолчанию
	port := os.Getenv("TODO_PORT")
	if port == "" {
		port = defaultPort
	}

	// Инициализируем API обработчики
	api.Init()

	// Настраиваем файл-сервер для обслуживания статических файлов
	http.Handle("/", http.FileServer(http.Dir(webDir)))

	// Запускаем сервер
	fmt.Printf("Сервер запущен на порту %s\n", port)
	fmt.Printf("Веб-интерфейс: http://localhost:%s\n", port)
	log.Fatal(http.ListenAndServe(":"+port, nil))
}
